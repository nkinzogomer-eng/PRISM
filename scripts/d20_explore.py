"""D2.0 generate a real-EVM test from a model-produced, bounded search trace.

Generated Solidity is only a *verification experiment*. The planner's model
must agree with local EVM balances and share accounting or CI must fail.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
from hashlib import sha256
import json
from pathlib import Path

from prism.defi_search import INITIAL, MAX_DEPTH, replay, search, violated


def _step(op: str, amount: int) -> str:
    if op == "deposit_attacker":
        return f"attacker.deposit(vault, {amount});"
    if op == "deposit_victim":
        return f"victim.deposit(vault, {amount});"
    if op == "donate":
        return f"attacker.donate(token, vault, {amount});"
    if op == "redeem_attacker":
        return "attacker.redeemAll(vault);"
    raise ValueError("unknown action")


def _guarded_step(op: str, amount: int) -> str:
    if op == "deposit_victim":
        return (f"bool rejected = false;\n"
                f"try victim.deposit(vault, {amount}) returns (uint256 minted) {{\n"
                "    // Any successful positive-asset deposit MUST mint positive shares.\n"
                "    require(minted > 0, \"accepted-zero-share-deposit\");\n"
                "} catch { rejected = true; }\n"
                "require(rejected, \"patched-vault-did-not-reject\");")
    raise ValueError("unexpected patched-block location; model contract drift")


def _solidity(plan: tuple[tuple[str, int], ...], expected, protected_prefix,
              rejected_at: int) -> str:
    trace = "\n        ".join(_step(op, amount) for op, amount in plan)
    prefix = "\n        ".join(_step(op, amount) for op, amount in plan[:rejected_at])
    blocked = _guarded_step(*plan[rejected_at])
    return f'''// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// Auto-generated by scripts/d20_explore.py. NOT a manually curated oracle.
// Reproduce this test with the recorded action sequence and contract checksum.
import {{LocalAsset, LocalVault, LocalActor}} from "../src/VaultFixture.sol";

contract GeneratedDiscoveryTest {{
    function setupActors(bool guarded)
        internal returns (LocalAsset token, LocalVault vault,
                          LocalActor attacker, LocalActor victim)
    {{
        token = new LocalAsset();
        vault = new LocalVault(token, guarded);
        attacker = new LocalActor();
        victim = new LocalActor();
        token.mint(address(attacker), {INITIAL});
        token.mint(address(victim), {INITIAL});
        attacker.approveVault(token, vault);
        victim.approveVault(token, vault);
    }}

    function testGeneratedVulnerableTraceAndExactAccounting() external {{
        (LocalAsset token, LocalVault vault, LocalActor attacker, LocalActor victim) =
            setupActors(false);
        {trace}
        require(token.balanceOf(address(attacker)) == {expected.attacker_wallet},
                "model-EVM-attacker-wallet-mismatch");
        require(token.balanceOf(address(victim)) == {expected.victim_wallet},
                "model-EVM-victim-wallet-mismatch");
        require(token.balanceOf(address(vault)) == {expected.vault_assets},
                "model-EVM-vault-assets-mismatch");
        require(vault.balanceOf(address(attacker)) == {expected.attacker_shares},
                "model-EVM-attacker-shares-mismatch");
        require(vault.balanceOf(address(victim)) == {expected.victim_shares},
                "model-EVM-victim-shares-mismatch");
        require(vault.totalSupply() == {expected.share_supply},
                "model-EVM-share-supply-mismatch");
        require(token.balanceOf(address(attacker)) > {INITIAL}, "no-attacker-profit");
        require(token.balanceOf(address(victim)) < {INITIAL}, "no-victim-loss");
    }}

    function testSameGeneratedTraceBlockedByGuardedVariant() external {{
        (LocalAsset token, LocalVault vault, LocalActor attacker, LocalActor victim) =
            setupActors(true);
        {prefix}
        {blocked}
        require(token.balanceOf(address(victim)) == {protected_prefix.victim_wallet},
                "guarded-wallet-model-mismatch");
        require(token.balanceOf(address(vault)) == {protected_prefix.vault_assets},
                "guarded-asset-model-mismatch");
    }}
}}
'''


def run(out: Path, root: Path, *, max_depth: int = MAX_DEPTH) -> dict:
    asset = root / "src" / "VaultFixture.sol"
    if not asset.is_file():
        raise FileNotFoundError(asset)
    source_sha = sha256(asset.read_bytes()).hexdigest()
    comparisons = [
        search(policy="breadth_first", protected=False, depth=max_depth),
        search(policy="goal_first", protected=False, depth=max_depth),
        search(policy="breadth_first", protected=True, depth=max_depth),
        search(policy="goal_first", protected=True, depth=max_depth),
    ]
    basic, target, fixed_basic, fixed_target = comparisons
    if not basic.found or not target.found:
        raise RuntimeError("cannot independently find exploit even in toy model")
    if fixed_basic.found or fixed_target.found:
        raise RuntimeError("model says the guarded vault is exploitable")
    predicted, rejected = replay(target.plan, protected=False)
    if rejected is not None or not violated(predicted):
        raise RuntimeError("invalid candidate model witness")
    safe_prefix, safe_reject = replay(target.plan, protected=True)
    if safe_reject is None or target.plan[safe_reject][0] != "deposit_victim":
        raise RuntimeError("guarded variant did not reject a zero-mint deposit")
    # A security finding is not counted as EVM-confirmed until the generated
    # test executes. All the counts here belong to the MODEL search only.
    root_test = root / "test"
    root_test.mkdir(parents=True, exist_ok=True)
    generated = root_test / "GeneratedDiscovery.t.sol"
    generated.write_text(_solidity(target.plan, predicted, safe_prefix, safe_reject),
                         encoding="utf-8")
    out.mkdir(parents=True, exist_ok=True)
    record = {
        "phase": "DeFi D2.0",
        "status": "CANDIDATE_ONLY_AWAITING_EVM",
        "fixture_sha256": source_sha,
        "plan": [{"action": op, "amount": amount} for op, amount in target.plan],
        "predicted_model_state": asdict(predicted),
        "predicted_guarded_rejection_step": safe_reject,
        "baseline_and_experiment": [asdict(p) for p in comparisons],
        "decision": "Do not claim SOTA advantage on manually tailored, synthetic vault",
        "constraints": [
            "Only a local toy vault, fixed model and bounded action alphabet",
            "Goal-first heuristic is hand-authored from a known safety property",
            "Model behavior is not the actual EVM; Foundry test must validate",
            "Breadth-first is a toy exhaustive baseline, not Foundry/Echidna/Halmos",
            "No true zero-day, critical-severity label or production exploit",
            "Warm models exclude solc install/network and end-to-end build costs",
            "Unmodeled cross-contract actions and real-world states remain UNKNOWN",
        ],
    }
    (out / "candidate.json").write_text(json.dumps(record, indent=2, sort_keys=True)+"\n")
    print("D2.0 bounded model explorer")
    for item in comparisons:
        print(item.policy, "guarded", item.protected, "found", item.found,
              "expanded", item.states_expanded,
              "transitions", item.transitions_attempted,
              "runtime_seconds", round(item.wall_seconds, 6),
              "budget_exhausted", item.budget_exhausted)
    print("Generated candidate:", " -> ".join(f"{op}({amt})" for op, amt in target.plan))
    print("Independent Foundry verification pending")
    return record


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--output", required=True, type=Path)
    cli.add_argument("--root", required=True, type=Path)
    cli.add_argument("--depth", type=int, default=MAX_DEPTH)
    args = cli.parse_args()
    run(args.output, args.root, max_depth=args.depth)
